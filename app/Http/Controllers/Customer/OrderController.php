<?php

namespace App\Http\Controllers\Customer;

use App\Http\Controllers\Controller;
use App\Models\Customer;
use App\Models\Order;
use App\Models\OrderItem;
use Illuminate\Http\Request;

class OrderController extends Controller
{
    /**
     * Show all orders of logged-in customer.
     */
    public function index()
    {
        $customer = Customer::findOrFail(session('customer_id'));

        $orders = Order::where('customer_id', $customer->id)
            ->with('items')
            ->latest()
            ->paginate(10);

        return view('customer.orders', compact('customer', 'orders'));
    }

    /**
     * Show single order detail.
     */
    public function show($id)
    {
        $customer = Customer::findOrFail(session('customer_id'));

        $order = Order::with('items')
            ->where('customer_id', $customer->id)
            ->findOrFail($id);

        return view('customer.order-detail', compact('customer', 'order'));
    }

    /**
     * Show the Order Tracking page - reuses Order::statusSteps() to
     * work out which steps in the timeline are already complete.
     */
    public function tracking($id)
    {
        $customer = Customer::findOrFail(session('customer_id'));

        $order = Order::with('items')
            ->where('customer_id', $customer->id)
            ->findOrFail($id);

        $steps = Order::statusSteps();
        $currentIndex = array_search($order->status, $steps);
        // Cancelled orders aren't part of the normal timeline - treat
        // as "no steps completed" instead of crashing on array_search === false.
        $currentIndex = $currentIndex === false ? -1 : $currentIndex;

        return view('customer.order-tracking', compact('customer', 'order', 'steps', 'currentIndex'));
    }

    /**
     * Show checkout page with cart items.
     */
    public function checkout()
    {
        $customer = Customer::findOrFail(session('customer_id'));

        $cart = session()->get('cart', []);

        if (empty($cart)) {
            return redirect('/cart')->with('error', 'Your cart is empty.');
        }

        return view('customer.checkout', compact('customer', 'cart'));
    }

    /**
     * Place order — create order + order items.
     * Order number is auto-generated by the Order model (booted method).
     */
    public function placeOrder(Request $request)
    {
        $customer = Customer::findOrFail(session('customer_id'));

        // Basic checkout validation. Card numbers are validated with the
        // Luhn algorithm for a realistic card-number format; this does NOT
        // charge a real card or connect to a payment gateway.
        $request->validate([
            'full_name' => 'required|string|min:3',
            'phone' => 'required|string|min:10',
            'shipping_address' => 'required|string|min:10',
            'payment_method' => 'required|in:VPP / Pay on Delivery,Credit / Debit Card,Cheque',
            'card_number' => 'nullable|string',
            'card_expiry' => 'nullable|string',
            'cheque_number' => 'nullable|string|max:100',
        ]);

        $cardLast4 = null;

        if ($request->payment_method === 'Credit / Debit Card') {
            $cardNumber = preg_replace('/\D+/', '', (string) $request->card_number);

            if (strlen($cardNumber) !== 16 || !$this->passesLuhn($cardNumber)) {
                return back()->withInput()->withErrors([
                    'card_number' => 'Please enter a valid credit/debit card number.',
                ]);
            }

            if (!preg_match('/^(0[1-9]|1[0-2])\/[0-9]{2}$/', (string) $request->card_expiry)) {
                return back()->withInput()->withErrors([
                    'card_expiry' => 'Please enter a valid expiry date in MM/YY format.',
                ]);
            }

            [$month, $year] = explode('/', $request->card_expiry);
            $expiry = (int) ('20' . $year) * 100 + (int) $month;
            $current = (int) now()->format('Ym');

            if ($expiry < $current) {
                return back()->withInput()->withErrors([
                    'card_expiry' => 'This card has expired.',
                ]);
            }

            $cardLast4 = substr($cardNumber, -4);
        }

        if ($request->payment_method === 'Cheque' && blank($request->cheque_number)) {
            return back()->withInput()->withErrors([
                'cheque_number' => 'Cheque number is required for cheque payment.',
            ]);
        }

        $cart = session()->get('cart', []);

        if (empty($cart)) {
            return redirect('/cart')->with('error', 'Your cart is empty.');
        }

        // Calculate subtotal (without shipping)
        $subtotal = array_reduce($cart, function ($sum, $item) {
            return $sum + ($item['price'] * $item['quantity']);
        }, 0);

        // Shipping fee (example: free shipping over $100, otherwise $8)
        $shippingFee = $subtotal >= 100 ? 0 : 8;

        // Total amount = subtotal + shipping
        $total = $subtotal + $shippingFee;

        // ============================================================
        // CREATE ORDER — ORDER NUMBER AUTO-GENERATED BY MODEL
        // NO NEED to call generateOrderNumber() manually
        // ============================================================
        $order = Order::create([
            'customer_id' => $customer->id,
            'status' => Order::STATUS_PENDING,
            'payment_method' => $request->payment_method,
            'card_last4' => $cardLast4,
            'cheque_number' => $request->payment_method === 'Cheque' ? $request->cheque_number : null,
            'subtotal' => $subtotal,
            'shipping_fee' => $shippingFee,
            'total_amount' => $total,
            'shipping_address' => $request->shipping_address,
            // 'shipping_address_id' and 'billing_address_id' can be added later
        ]);

        // Create order items
        // NOTE: keys must match OrderItem::$fillable / the order_items
        // table columns exactly - "unit_price", not "product_price".
        foreach ($cart as $item) {
            OrderItem::create([
                'order_id' => $order->id,
                'product_name' => $item['name'],
                'product_image' => $item['image'] ?? null,
                'unit_price' => $item['price'],
                'quantity' => $item['quantity'],
                'subtotal' => $item['price'] * $item['quantity'],
            ]);
        }

        // Clear cart (both the PHP session copy used for checkout)
        session()->forget('cart');

        return redirect()->route('customer.orders')
            ->with('success', 'Order placed successfully! Order #' . $order->order_number);
    }

    /** Validate a card number using the standard Luhn checksum. */
    private function passesLuhn(string $number): bool
    {
        $sum = 0;
        $double = false;

        for ($i = strlen($number) - 1; $i >= 0; $i--) {
            $digit = (int) $number[$i];

            if ($double) {
                $digit *= 2;
                if ($digit > 9) {
                    $digit -= 9;
                }
            }

            $sum += $digit;
            $double = !$double;
        }

        return $sum % 10 === 0;
    }

    /**
     * Cancel order (only pending orders can be cancelled).
     */
    public function cancel($id)
    {
        $customer = Customer::findOrFail(session('customer_id'));

        $order = Order::where('customer_id', $customer->id)->findOrFail($id);

        if ($order->status !== Order::STATUS_PENDING) {
            return redirect()->route('customer.orders')->with('error', 'Only pending orders can be cancelled.');
        }

        $order->update(['status' => 'Cancelled']);

        return redirect()->route('customer.orders')->with('success', 'Order cancelled successfully.');
    }
}
